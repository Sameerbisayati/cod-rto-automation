import { useEffect, useState } from "react";
import "./DecisionAnalytics.css";

const API_URL = "http://127.0.0.1:8000";

const actionLabels = {
  SHIP_AS_IS: "Ship As-Is",
  WHATSAPP_CONFIRMATION: "WhatsApp Confirmation",
  PREPAID_NUDGE: "Prepaid Nudge",
  HOLD_REVIEW: "Hold / Review",
};

function DecisionAnalytics() {
  const [orders, setOrders] = useState([]);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState("");

  useEffect(() => {
    const fetchDecisions = async () => {
      try {
        const response = await fetch(`${API_URL}/api/decisions`);

        if (!response.ok) {
          throw new Error("Unable to load decision analytics.");
        }

        const data = await response.json();
        setOrders(Array.isArray(data) ? data : data.decisions || []);
        setError("");
      } catch (err) {
        setError(err.message);
      } finally {
        setLoading(false);
      }
    };

    fetchDecisions();
  }, []);

  if (loading) {
    return <p className="analytics-message">Loading decision analytics...</p>;
  }

  if (error) {
    return <p className="analytics-error">{error}</p>;
  }

  const total = orders.length;

  const actionCounts = Object.keys(actionLabels).map((action) => ({
    action,
    label: actionLabels[action],
    count: orders.filter((order) => order.action === action).length,
  }));

  const riskCounts = {
    low: orders.filter((order) => Number(order.risk_score) <= 25).length,
    medium: orders.filter(
      (order) =>
        Number(order.risk_score) > 25 &&
        Number(order.risk_score) <= 55
    ).length,
    high: orders.filter((order) => Number(order.risk_score) > 55).length,
  };

  const riskGroups = [
    { label: "Low Risk", count: riskCounts.low, className: "low" },
    { label: "Medium Risk", count: riskCounts.medium, className: "medium" },
    { label: "High Risk", count: riskCounts.high, className: "high" },
  ];

  const getPercentage = (count) =>
    total ? ((count / total) * 100).toFixed(1) : "0.0";

  return (
    <section className="decision-analytics">
      <div className="analytics-heading">
        <div>
          <h2>Decision Analytics</h2>
          <p>Overview of recommended actions and order risk levels</p>
        </div>
        <span className="analytics-total">{total} Orders Analyzed</span>
      </div>

      <div className="analytics-columns">
        <div className="analytics-panel">
          <h3>Decision Distribution</h3>

          {actionCounts.map((item) => (
            <div className="analytics-item" key={item.action}>
              <div className="analytics-item-heading">
                <span>{item.label}</span>
                <strong>
                  {item.count} ({getPercentage(item.count)}%)
                </strong>
              </div>

              <div className="analytics-track">
                <div
                  className={`analytics-fill action-${item.action.toLowerCase()}`}
                  style={{
                    width: `${getPercentage(item.count)}%`,
                  }}
                ></div>
              </div>
            </div>
          ))}
        </div>

        <div className="analytics-panel">
          <h3>Risk Score Distribution</h3>

          {riskGroups.map((item) => (
            <div className="analytics-item" key={item.label}>
              <div className="analytics-item-heading">
                <span>{item.label}</span>
                <strong>
                  {item.count} ({getPercentage(item.count)}%)
                </strong>
              </div>

              <div className="analytics-track">
                <div
                  className={`analytics-fill risk-${item.className}`}
                  style={{
                    width: `${getPercentage(item.count)}%`,
                  }}
                ></div>
              </div>
            </div>
          ))}
        </div>
      </div>

      <p className="analytics-note">
        These figures represent recommendations generated by the current
        decision rules. They do not represent confirmed prevented RTOs.
      </p>
    </section>
  );
}

export default DecisionAnalytics;